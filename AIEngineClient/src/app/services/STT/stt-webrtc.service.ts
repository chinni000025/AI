import { Injectable } from '@angular/core';
import { BehaviorSubject, Observable, Subject } from 'rxjs';
@Injectable({
    providedIn: 'root'
})
export class SttWebRtcService {
    private peerConnection: RTCPeerConnection | null = null;
    private readonly iceCandidateSubject = new Subject<RTCIceCandidateInit | null>();
    private readonly connectionStateSubject = new BehaviorSubject<RTCPeerConnectionState>('new');
    private readonly pendingRemoteIceCandidates: (RTCIceCandidateInit | null)[] = [];
    private isRemoteDescriptionSet = false;
    private isApplyingRemoteCandidates = false;

    /**
     * Emits ICE candidates generated by the browser.
     *
     * A null value indicates that ICE candidate gathering
     * has completed.
     */
    readonly iceCandidate$: Observable<RTCIceCandidateInit | null> =
        this.iceCandidateSubject.asObservable();

    /**
     * Emits changes in the WebRTC peer connection state.
     */
    readonly connectionState$: Observable<RTCPeerConnectionState> =
        this.connectionStateSubject.asObservable();

    get isInitialized(): boolean {
        return this.peerConnection !== null;
    }

    /**
     * Creates the WebRTC peer connection and attaches
     * the microphone audio tracks.
     *
     * ICE configuration must be supplied by the caller.
     */
    initialize(stream: MediaStream, configuration: RTCConfiguration): void {
        if (this.peerConnection) {
            throw new Error('A WebRTC peer connection is already initialized.');
        }

        if (!stream || stream.getAudioTracks().length === 0) {
            throw new Error('A valid microphone audio stream is required.');
        }

        this.pendingRemoteIceCandidates.length = 0;
        this.isRemoteDescriptionSet = false;
        this.isApplyingRemoteCandidates = false;
        const peerConnection = new RTCPeerConnection(configuration);
        this.peerConnection = peerConnection;
        this.connectionStateSubject.next('new');

        peerConnection.addEventListener('icecandidate', event => {
            if (event.candidate) {
                this.iceCandidateSubject.next(
                    event.candidate.toJSON()
                );
            } else {
                this.iceCandidateSubject.next(null);
            }
        });

        peerConnection.addEventListener('connectionstatechange', () => {
            this.connectionStateSubject.next(
                peerConnection.connectionState
            );
        });

        stream.getAudioTracks().forEach(track => {
            peerConnection.addTrack(track, stream);
        });
    }

    /**
     * Creates an SDP offer and sets it as the local description.
     */
    async createOffer(): Promise<RTCSessionDescriptionInit> {

        const peerConnection = this.getPeerConnection();
        const offer = await peerConnection.createOffer();
        await peerConnection.setLocalDescription(offer);

        if (!peerConnection.localDescription) {
            throw new Error('Failed to create the local WebRTC description.');
        }

        return peerConnection.localDescription.toJSON();
    }

    /**
     * Applies the remote SDP answer received from the backend.
     */
    async setRemoteDescription(description: RTCSessionDescriptionInit): Promise<void> {
        const peerConnection = this.getPeerConnection();
        await peerConnection.setRemoteDescription(description);
        this.isRemoteDescriptionSet = true;
        await this.flushPendingRemoteIceCandidates();
    }

    async addIceCandidate(candidate: RTCIceCandidateInit | null): Promise<void> {
        const peerConnection = this.getPeerConnection();
        if (!this.isRemoteDescriptionSet || this.isApplyingRemoteCandidates) {
            this.pendingRemoteIceCandidates.push(candidate);
            return;
        }
        await peerConnection.addIceCandidate(candidate);
    }

    private async flushPendingRemoteIceCandidates(): Promise<void> {
        const peerConnection = this.getPeerConnection();

        if (!this.isRemoteDescriptionSet || this.isApplyingRemoteCandidates) {
            return;
        }

        this.isApplyingRemoteCandidates = true;

        try {
            while (this.pendingRemoteIceCandidates.length > 0) {
                const candidate = this.pendingRemoteIceCandidates.shift()!;
                await peerConnection.addIceCandidate(candidate);
            }
        } catch (error) {
            // Preserve candidates that have not yet been processed.
            throw error;
        } finally {
            this.isApplyingRemoteCandidates = false;
        }
    }
    /**
     * Closes the peer connection and releases its references.
     *
     * Microphone tracks are owned by SttMicrophoneService,
     * so they must be released separately.
     */
    close(): void {
        if (!this.peerConnection) {
            return;
        }
        this.peerConnection.close();
        this.peerConnection = null;
        this.pendingRemoteIceCandidates.length = 0;
        this.isRemoteDescriptionSet = false;
        this.isApplyingRemoteCandidates = false;
        this.connectionStateSubject.next('closed');
    }

    private getPeerConnection(): RTCPeerConnection {

        if (!this.peerConnection) {
            throw new Error('The WebRTC peer connection has not been initialized.');
        }

        return this.peerConnection;
    }
}
